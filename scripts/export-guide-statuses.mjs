// Writes client/src/lib/nepal-guide-statuses.json: the tourist-visa status
// of every country that has a full, hand-checked guide in
// server/data/visa-profiles.json, in the passport-index vocabulary the
// client uses. The client can't bundle the 240 KB profiles file, but its
// visa checker and lists must agree with the guides (which are
// Nepal-specific and more current than the community dataset).
// Run by script/build.ts before every build; commit the output so dev works.
import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const profiles = JSON.parse(readFileSync(path.join(root, "server/data/visa-profiles.json"), "utf-8"));

// Guide statuses -> passport-index statuses. Sponsor/employer programmes
// are applied for before travel, so they read as a visa required.
const TO_INDEX = {
  visa_free: "visa_free",
  visa_on_arrival: "visa_on_arrival",
  evisa: "evisa",
  embassy_visa: "sticker_visa",
  sponsor_program: "sticker_visa",
  employer_petition: "sticker_visa",
};

const statuses = {};
for (const p of profiles) {
  if (p.fromCountryCode !== "NP" || p.category !== "tourist") continue;
  statuses[p.countryCode] = TO_INDEX[p.status] ?? "sticker_visa";
}

const sorted = Object.fromEntries(Object.keys(statuses).sort().map((k) => [k, statuses[k]]));
writeFileSync(
  path.join(root, "client/src/lib/nepal-guide-statuses.json"),
  JSON.stringify({ _comment: "Generated by scripts/export-guide-statuses.mjs from server/data/visa-profiles.json — do not edit by hand.", statuses: sorted }, null, 2) + "\n",
);
console.log(`✓ ${Object.keys(sorted).length} guide statuses written`);
