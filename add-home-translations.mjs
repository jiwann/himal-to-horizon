// Language code order matching the file structure
const langOrder = ["en","es","pt","fr","ne","ar","hi","bn","ko","ja","zh","de","ru","pl","fi","sv","no","vi","th"];

// Find the pattern for each language block and inject the new keys
// Each language block starts with something like:
// const en: Record<TranslationKey, string> = {
// We'll find "footer.blog_link" in each language block and insert after it

for (const lang of langOrder) {
  const keys = translations[lang];
  if (!keys) {
    console.error(`Missing translations for language: ${lang}`);
    continue;
  }
  
  const newEntries = Object.entries(keys)
    .map(([k, v]) => `  "${k}": ${JSON.stringify(v)},`)
    .join("\n");
  
  // Find the footer.blog_link entry for this language and insert after it
  // We need to be careful to only replace once per language
  // Strategy: find "footer.blog_link": "..." followed by the next entry
  // The pattern is: "footer.blog_link": "<translation>",
  // We'll add our new entries after it
  
  // Count occurrences to find the right one
  const marker = '"footer.blog_link"';
  
  // Find all positions of this marker
  let pos = 0;
  let count = 0;
  const langIndex = langOrder.indexOf(lang);
  
  // Find the (langIndex+1)th occurrence
  let foundPos = -1;
  while (count <= langIndex) {
    const idx = src.indexOf(marker, pos);
    if (idx === -1) break;
    foundPos = idx;
    pos = idx + 1;
    count++;
  }
  
  if (foundPos === -1) {
    console.error(`Could not find footer.blog_link for language ${lang}`);
    continue;
  }
  
  // Find the end of this line (after the value and comma)
  const lineEnd = src.indexOf("\n", foundPos);
  if (lineEnd === -1) {
    console.error(`Could not find line end for ${lang}`);
    continue;
  }
  
  src = src.slice(0, lineEnd + 1) + newEntries + "\n" + src.slice(lineEnd + 1);
  console.log(`✓ Added translations for ${lang}`);
}

writeFileSync(filePath, src, "utf8");
